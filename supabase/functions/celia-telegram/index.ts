export function makeHandler(deps: Deps) {
  const { env, store } = deps;
  const fetchFn = deps.fetchFn ?? fetch;
  const log = deps.log ?? ((l: string) => console.log(l));
  const token = () => (env("CELIA_TELEGRAM_TOKEN") || "").trim();
  const owners = () => new Set((env("CELIA_OWNER_IDS") || "").split(/[\s,]+/).filter((s) => /^\d{1,20}$/.test(s)));
  const providers = () => deps.providers ?? defaultProviders(env, fetchFn);
  const json = (body: unknown, status = 200) =>
    new Response(JSON.stringify(body), { status, headers: { "Content-Type": "application/json; charset=utf-8" } });

  async function process(update: Record<string, unknown>): Promise<string> {
    const msg = update.message as TgMessage | undefined;
    if (!msg || typeof msg.text !== "string" || !msg.text.trim()) return "ignored_non_text";
    if (msg.chat?.type !== "private") return "ignored_group";
    const tg = new TelegramApi(token(), fetchFn);
    const chatId = msg.chat.id;
    const fromId = String(msg.from?.id ?? "");
    const allowed = owners();
    if (allowed.size === 0) {
      await tg.call("sendMessage", {
        chat_id: chatId,
        text: `أنا سيليا 🌿 لم يُضبط مالكي بعد.\nمعرّفك على تيليجرام: ${fromId}\n` +
          "أضفه في أسرار Supabase باسم CELIA_OWNER_IDS ثم راسلني من جديد.",
      });
      return "onboarding";
    }
    if (!allowed.has(fromId)) return "ignored_sender";

    const text = msg.text.slice(0, 4000);
    const anim = new Animator(tg, chatId, deps.sleep, env("CELIA_ANIMATION") !== "0");
    if (/^\/(start|help)\b/.test(text)) {
      await tg.call("sendMessage", { chat_id: chatId, text: GREETING });
      return "greeted";
    }
    const cmd = /^\/memory\b/.test(text) ? { kind: "list" as const, argument: "" } : parseMemoryCommand(text);
    let book: MemoryBook | null = null;
    try {
      book = new MemoryBook(await store.loadMemory(), store, deps.clock);
    } catch {
      book = null;
    }

    if (cmd) {
      await anim.react(msg.message_id, "👀");
      const out = book
        ? await book.executeDurably(cmd, `telegram:${msg.message_id}`)
        : { stage: "memory_unavailable", reply: "ذاكرتي الدائمة غير متاحة الآن، لذلك لم أحفظ ولم أحذف شيئاً. أعد المحاولة بعد قليل." };
      await tg.call("sendMessage", { chat_id: chatId, text: out.reply });
      if (out.stage === "memory_saved") await anim.react(msg.message_id, "✍");
      if (out.stage === "memory_forgotten") await anim.react(msg.message_id, "👌");
      return out.stage;
    }

    const mode = detectMode(text);
    const memories = book ? book.recall(text, 6) : [];
    await anim.react(msg.message_id, "👀");
    await anim.start(mode);
    let history: Turn[] = [];
    try {
      history = await store.loadTurns(String(chatId), 16);
    } catch {
      history = [];
    }
    const answer = await completeFreeFirst(providers(), renderOwnerPrompt(mode, memories), history, text);
    await anim.finish(answer ? answer.text : P.owner_fallback);
    if (!answer) return "no_provider_available";
    try {
      await store.appendTurns(String(chatId), text, answer.text);
    } catch {
      // history is best-effort; the reply was already delivered
    }
    log(`celia mode=${mode} provider=${answer.provider} tier=free_tier cost_usd=0.00 memories=${memories.length}`);
    return "replied";
  }

  return async (req: Request): Promise<Response> => {
    const url = new URL(req.url);
    const route = routeOf(url.pathname);
    if (req.method === "GET" && route === "/healthz") {
      let db = false;
      try {
        db = await store.healthz();
      } catch {
        db = false;
      }
      return json({
        ok: db && !!token(),
        service: "celia-telegram",
        telegram: !!token(),
        owners: owners().size > 0,
        providers: providers().filter((p) => p.configured()).length,
        store: db,
      }, db ? 200 : 503);
    }
    if (req.method === "GET" && route === "/setup") {
      if (!token()) return json({ ok: false, message: "أضف CELIA_TELEGRAM_TOKEN في أسرار Supabase أولاً." }, 503);
      const base = (env("SUPABASE_URL") || "").replace(/\/+$/, "");
      const tg = new TelegramApi(token(), fetchFn);
      const hook = await tg.call("setWebhook", {
        url: `${base}/functions/v1/celia-telegram/telegram`,
        secret_token: await webhookSecret(token()),
        allowed_updates: ["message"],
        max_connections: 10,
      });
      await tg.call("setMyCommands", {
        commands: [{ command: "start", description: "تعريف بسيليا" }, { command: "memory", description: "ماذا تتذكرين؟" }],
      });
      const me = await tg.call("getMe", {});
      const bot = typeof me?.username === "string" ? `@${me.username}` : null;
      return json(hook
        ? { ok: true, bot, message: `تم ربط سيليا بتيليجرام ✅ افتح ${bot ?? "البوت"} وأرسل /start` }
        : { ok: false, message: "رفض تيليجرام ربط الـwebhook؛ تأكد من CELIA_TELEGRAM_TOKEN." }, hook ? 200 : 502);
    }
    if (req.method !== "POST" || route !== "/telegram") return new Response(null, { status: 404 });
    if (!token()) return new Response(null, { status: 503 });
    const given = req.headers.get("X-Telegram-Bot-Api-Secret-Token") || "";
    if (!constantTimeEqual(given, await webhookSecret(token()))) return new Response(null, { status: 401 });
    const raw = await req.text();
    if (raw.length > 1_000_000) return new Response(null, { status: 413 });
    let update: Record<string, unknown>;
    try {
      update = JSON.parse(raw);
    } catch {
      return new Response(null, { status: 400 });
    }
    const updateId = Number(update?.update_id);
    if (!Number.isSafeInteger(updateId)) return new Response(null, { status: 400 });
    let first = true;
    try {
      first = await store.claimUpdate(updateId);
    } catch {
      first = true; // availability over de-duplication; memory writes still fail honestly
    }
    if (!first) {
      log("celia stage=duplicate_update");
      return json({ ok: true });
    }
    const work = process(update)
      .then((stage) => log(`celia stage=${label(stage)}`))
      .catch((e) => log(`celia stage=error reason=${e instanceof Error ? e.name : "unknown"}`));
    // Answer Telegram at once; the reply (and its animation) continues in the background.
    if (deps.waitUntil) deps.waitUntil(work);
    else await work;
    return json({ ok: true });
  };
}

