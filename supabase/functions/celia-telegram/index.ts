const EXPLICIT_RE = new RegExp(`(?<!${W})(?:وضع|mode)\\s+(?:ال)?(${W}+)`, "u");

export function detectMode(text: string): Mode {
  const norm = normalizeForMode(text);
  const m = norm.match(EXPLICIT_RE);
  if (m && Object.hasOwn(P.explicit_modes, m[1])) return P.explicit_modes[m[1]];
  for (const [mode, keywords] of P.mode_keywords) {
    for (const k of keywords) {
      const ascii = Array.from(k).every((c) => c.charCodeAt(0) < 128); // python str.isascii()
      const hit = ascii ? norm.includes(" " + k.trim()) : norm.includes(k);
      if (hit) return mode;
    }
  }
  return "companion";
}

function memoryBlock(memories: readonly string[]): string {
  const lines: string[] = [];
  let used = 0;
  for (const item of memories) {
    const line = `- ${item.trim()}`;
    if (!item.trim() || used + cpLen(line) > P.memory_block_max_chars) break;
    lines.push(line);
    used += cpLen(line);
  }
  return lines.length ? `${P.memory_header}\n${lines.join("\n")}` : "";
}

/** Owner-scope prompt (python render_system_prompt(Audience.OWNER, mode, memories)). */
export function renderOwnerPrompt(mode: Mode, memories: readonly string[] = []): string {
  const parts = [
    P.identity_text,
    P.owner_scope,
    `وضع العمل الحالي: ${P.mode_labels[mode]}. ${P.mode_instructions[mode]}`,
    P.honesty_text,
    P.owner_memory_text,
  ];
  const block = memoryBlock(memories);
  if (block) parts.push("\n" + block);
  return parts.join(" ");
}

// -------------------------------------------------------- memory commands
export type Command = { kind: "remember" | "forget" | "list"; argument: string };
const ADDRESS = "^(?:يا\\s+)?(?:سيليا|celia)?[\\s،,:]*";
const REMEMBER_RE = new RegExp(
  ADDRESS + `(?:تذكري|احفظي|سجلي|remember|save)${B}\\s*(?:[:：\\-–]|\\s(?:ان|that)${B})\\s*(.+)$`,
  "su",
);
const FORGET_RE = new RegExp(
  ADDRESS + `(?:انسي|امسحي|forget)${B}\\s*(?:(?:رقم|number|#)\\s*(${D}+)|(${D}+)|[:：\\-–]\\s*(.+))\\s*$`,
  "su",
);
const LIST_RE = new RegExp(
  ADDRESS +
    "(?:ماذا تتذكرين|ماذا تتذكري|ايش تتذكري|بتفتكري ايه|اعرضي الذاكره|ذاكرتك|" +
    "what do you remember|show memory)\\s*[؟?!.]*$",
  "u",
);

function stripChars(s: string, chars: string): string {
  const a = cps(s);
  let i = 0, j = a.length;
  while (i < j && chars.includes(a[i])) i++;
  while (j > i && chars.includes(a[j - 1])) j--;
  return a.slice(i, j).join("");
}

function originalTail(text: string, normTail: string): string {
  const original = cps(text.trim());
  for (let i = 0; i < Math.min(original.length, 120); i++) {
    const candidate = original.slice(i).join("");
    if (normalizeBilingual(candidate) === normTail) return stripChars(candidate, " :：-–");
  }
  return normTail;
}

export function parseMemoryCommand(text: string): Command | null {
  const norm = normalizeBilingual(text || "");
  if (!norm) return null;
  if (LIST_RE.test(norm)) return { kind: "list", argument: "" };
  let m = norm.match(REMEMBER_RE);
  if (m) return { kind: "remember", argument: originalTail(text, m[1].trim()) };
  m = norm.match(FORGET_RE);
  if (m) {
    const n = m[1] || m[2];
    if (n) return { kind: "forget", argument: n };
    return { kind: "forget", argument: originalTail(text, m[3].trim()) };
  }
  return null;
}

const SENSITIVE = [
  new RegExp(`(?:كلمه\\s*(?:ال)?(?:سر|مرور)|باسورد|password|passwd|${B}pin${B})`, "iu"),
  new RegExp(`(?:رمز\\s*(?:ال)?تحقق|كود\\s*(?:ال)?تحقق|${B}otp${B}|verification code)`, "iu"),
  new RegExp(`${B}(?:${D}[ -]?){13,19}${B}`, "u"),
  new RegExp(`${B}[a-z]{2}${D}{2}[a-z0-9]{11,30}${B}`, "iu"),
  /(?:sk-|ghp_|gho_|github_pat_|xox[bap]-|aiza|hf_|xai-|glpat-|eyj)[a-z0-9_\-]{8,}/iu,
  new RegExp(`${B}[a-z0-9_\\-]{32,}${B}`, "iu"),
];

export function looksSensitive(text: string): boolean {
  const norm = normalizeBilingual(text);
  return SENSITIVE.some((p) => p.test(norm) || p.test(text));
}

export function classifyKind(text: string): Kind {
  const norm = ` ${normalizeBilingual(text)} `;
  for (const [kind, hints] of M.kind_hints) if (hints.some((h) => norm.includes(h))) return kind;
  return "semantic";
}

// ------------------------------------------------------------ memory book
export interface MemoryRecord {
  id: number;
  kind: Kind;
  text: string;
  source: string;
  created_at: string;
  confidence: number;
}
export type Outcome = { stage: string; reply: string };
export type Change = { insert: MemoryRecord } | { delete: number } | null;

/** Persists ONE change; throws on failure (the book rolls back). */
export interface MemoryStore {
  loadMemory(): Promise<MemoryRecord[]>;
  applyChange(change: Change): Promise<void>;
}

const STORE_FAILED =
  "لم أتمكن من الكتابة في ذاكرتي الدائمة الآن، فلم يتغير شيء. أعد المحاولة بعد قليل.";
const KINDS = new Set<Kind>(["personal", "project", "procedural", "semantic"]);

/** Port of python-2027 PersonalMemory (same replies, same ids, same rules). */
export class MemoryBook {
  records: MemoryRecord[];
  constructor(
    rows: unknown[],
    private store: MemoryStore,
    private clock: () => string = () => new Date().toISOString().replace(/\.\d{3}Z$/, "Z"),
    private max: number = M.default_max_records,
  ) {
    this.records = [];
    for (const r of rows) {
      const o = r as Partial<MemoryRecord>;
      const id = Number(o?.id);
      if (Number.isInteger(id) && id >= 1 && KINDS.has(o.kind as Kind) && typeof o.text === "string" && o.text.trim()) {
        this.records.push({
          id,
          kind: o.kind as Kind,
          text: o.text.trim(),
          source: String(o.source || "owner"),
          created_at: String(o.created_at || ""),
          confidence: Number(o.confidence ?? 1),
        });
      }
    }
    this.records.sort((a, b) => a.id - b.id);
  }

  async executeDurably(cmd: Command, source: string): Promise<Outcome> {
    const before = [...this.records];
    const [outcome, change] = this.execute(cmd, source);
    if (!change) return outcome;
    try {
      await this.store.applyChange(change);
    } catch {
      this.records = before;
      return { stage: "memory_store_failed", reply: STORE_FAILED };
    }
    return outcome;
  }

  execute(cmd: Command, source: string): [Outcome, Change] {
    if (cmd.kind === "remember") return this.remember(cmd.argument, source);
    if (cmd.kind === "forget") return this.forget(cmd.argument);
    return [this.describe(), null];
  }

  remember(text: string, source: string): [Outcome, Change] {
    const fact = (text || "").split(/\s+/u).filter(Boolean).join(" ");
    if (!fact) return [{ stage: "memory_empty", reply: "ماذا تريدني أن أتذكر؟ اكتب: «تذكّري: …» ثم المعلومة." }, null];
    if (looksSensitive(fact)) {
      return [{
        stage: "memory_refused_sensitive",
        reply: "لن أحفظ هذا 🔒 يبدو أنه بيانات حساسة (كلمة مرور، رمز تحقق، رقم بطاقة أو مفتاح). " +
          "احتفظ به في مدير كلمات المرور، لا في ذاكرتي.",
      }, null];
    }
    if (cpLen(fact) > M.max_record_chars) {
      return [{
        stage: "memory_too_long",
        reply: `المعلومة أطول من ${M.max_record_chars} حرف؛ لخّصها في سطر أو سطرين وأحفظها.`,
      }, null];
    }
    const key = normalizeBilingual(fact);
    const dup = this.records.find((r) => normalizeBilingual(r.text) === key);
    if (dup) return [{ stage: "memory_duplicate", reply: `هذه محفوظة عندي بالفعل برقم ${dup.id}.` }, null];
    if (this.records.length >= this.max) {
      return [{
        stage: "memory_full",
        reply: `ذاكرتي ممتلئة (${this.max} معلومة). احذف شيئاً بـ«انسي رقم …» ثم أعد المحاولة.`,
      }, null];
    }
    const rec: MemoryRecord = {
      id: Math.max(0, ...this.records.map((r) => r.id)) + 1,
      kind: classifyKind(fact),
      text: fact,
      source: cps(source).slice(0, 120).join("") || "owner",
      created_at: this.clock(),
      confidence: 1,
    };
    this.records.push(rec);
    return [{
      stage: "memory_saved",
      reply: `حفظتُ ✅ رقم ${rec.id} (${M.kind_labels[rec.kind]}): ${rec.text}\nلحذفها لاحقاً: «انسي رقم ${rec.id}».`,
    }, { insert: rec }];
  }

  forget(argument: string): [Outcome, Change] {
    const arg = (argument || "").trim().replace(/^#+/, "").trim(); // python: strip().lstrip("#").strip()
    const digits = normalizeBilingual(arg);
    let target: MemoryRecord[];
    if (/^[0-9]+$/.test(digits)) {
      target = this.records.filter((r) => r.id === Number(digits));
    } else {
      const stems = normalizeBilingual(arg).split(" ").filter(Boolean)
        .map((w) => (w.startsWith("ال") && cpLen(w) > 3 ? w.slice(2) : w)).filter(Boolean);
      target = this.records.filter((r) => stems.length > 0 && stems.every((s) => normalizeBilingual(r.text).includes(s)));
    }
    if (!target.length) {
      return [{ stage: "memory_not_found", reply: "لم أجد هذا في ذاكرتي. اكتب «ماذا تتذكرين؟» لترى الأرقام." }, null];
    }
    if (target.length > 1) {
      const ids = target.slice(0, 10).map((r) => r.id).join("، ");
      return [{ stage: "memory_ambiguous", reply: `أكثر من معلومة تطابق (${ids}). حدّد الرقم: «انسي رقم …».` }, null];
    }
    const rec = target[0];
    this.records = this.records.filter((r) => r.id !== rec.id);
    return [{ stage: "memory_forgotten", reply: `نسيتُ رقم ${rec.id} 🗑️: ${rec.text}` }, { delete: rec.id }];
  }

  describe(limit = 30): Outcome {
    if (!this.records.length) {
      return { stage: "memory_listed", reply: "ذاكرتي الدائمة فارغة حتى الآن. لتحفظ شيئاً اكتب: «تذكّري: …»." };
    }
    const newest = [...this.records].reverse().slice(0, limit);
    const lines = newest.map((r) => `${r.id}. [${M.kind_labels[r.kind]} · ${r.created_at.slice(0, 10)}] ${r.text}`);
    const more = this.records.length - newest.length;
    const tail = more > 0 ? `\n… و${more} أخرى.` : "";
    return {
      stage: "memory_listed",
      reply: `في ذاكرتي الدائمة 🧠 (العدد: ${this.records.length})\n${lines.join("\n")}${tail}\nللحذف: «انسي رقم …».`,
    };
  }

  /** Lexical cosine over unigrams+bigrams (python uses hashed vectors of the same tokens). */
  recall(query: string, k = 6): string[] {
    if (!this.records.length || k <= 0) return [];
    const q = tokenVector(query);
    const scored = this.records
      .map((r) => ({ r, s: cosine(q, tokenVector(r.text)) }))
      .sort((a, b) => b.s - a.s || b.r.id - a.r.id);
    let chosen = scored.filter((x) => x.s > 0.05).slice(0, k).map((x) => x.r);
    if (!chosen.length) chosen = [...this.records].reverse().slice(0, k);
    return chosen.map((r) => `#${r.id} (${M.kind_labels[r.kind]}، ${r.created_at.slice(0, 10)}): ${r.text}`);
  }
}

function tokenVector(text: string): Map<string, number> {
  const uni = normalizeBilingual(text || "").match(/[a-z0-9\u0600-\u06FF]+/g) ?? [];
  const toks = [...uni, ...uni.slice(1).map((t, i) => `${uni[i]}_${t}`)];
  const v = new Map<string, number>();
  for (const t of toks) v.set(t, (v.get(t) ?? 0) + 1);
  return v;
}

function cosine(a: Map<string, number>, b: Map<string, number>): number {
  let dot = 0, na = 0, nb = 0;
  for (const [t, x] of a) {
    na += x * x;
    dot += x * (b.get(t) ?? 0);
  }
  for (const y of b.values()) nb += y * y;
  return na && nb ? dot / Math.sqrt(na * nb) : 0;
}

