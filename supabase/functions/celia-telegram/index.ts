/** First configured free provider that answers wins; null => honest fallback. */
export async function completeFreeFirst(
  providers: Provider[],
  system: string,
  history: Turn[],
  user: string,
  timeoutMs = 25_000,
): Promise<{ text: string; provider: string } | null> {
  for (const p of providers) {
    if (!p.configured()) continue;
    try {
      const text = await p.complete(system, history, user, AbortSignal.timeout(timeoutMs));
      if (text) return { text, provider: p.name };
    } catch {
      // next free provider; the error body is never logged
    }
  }
  return null;
}

