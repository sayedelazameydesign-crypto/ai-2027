type Sleep = (ms: number) => Promise<void>;
const realSleep: Sleep = (ms) => new Promise((r) => setTimeout(r, ms));

export function splitForTelegram(text: string, limit = TG_LIMIT): string[] {
  const out: string[] = [];
  let rest = text;
  while (cpLen(rest) > limit) {
    const head = cps(rest).slice(0, limit).join("");
    const cut = Math.max(head.lastIndexOf("\n"), head.lastIndexOf(" "));
    const piece = cut > limit / 2 ? head.slice(0, cut) : head;
    out.push(piece);
    rest = rest.slice(piece.length).trimStart();
  }
  if (rest) out.push(rest);
  return out;
}

/** The "thinking" animation: 👀, typing…, animated placeholder, in-place reveal. */
export class Animator {
  private done = false;
  private placeholder: number | null = null;
  private loops: Promise<void>[] = [];
  constructor(
    private tg: TelegramApi,
    private chatId: number | string,
    private sleep: Sleep = realSleep,
    private animate = true,
  ) {}

  async react(messageId: number, emoji: string): Promise<void> {
    await this.tg.call("setMessageReaction", {
      chat_id: this.chatId,
      message_id: messageId,
      reaction: [{ type: "emoji", emoji }],
    });
  }

  async start(mode: Mode): Promise<void> {
    await this.tg.call("sendChatAction", { chat_id: this.chatId, action: "typing" });
    this.loops.push((async () => {
      for (let i = 0; i < 12 && !this.done; i++) {
        await this.sleep(4500);
        if (!this.done) await this.tg.call("sendChatAction", { chat_id: this.chatId, action: "typing" });
      }
    })());
    if (!this.animate) return;
    const head = `${MODE_BADGES[mode]} سيليا · ${P.mode_labels[mode]}`;
    const sent = await this.tg.call("sendMessage", { chat_id: this.chatId, text: `${head}\n${FRAMES[0]}` });
    this.placeholder = typeof sent?.message_id === "number" ? sent.message_id : null;
    if (this.placeholder === null) return;
    this.loops.push((async () => {
      for (let i = 1; i < 40 && !this.done; i++) {
        await this.sleep(900);
        if (this.done) break;
        await this.tg.call("editMessageText", {
          chat_id: this.chatId, message_id: this.placeholder, text: `${head}\n${FRAMES[i % FRAMES.length]}`,
        });
      }
    })());
  }

  /** Stop the animation and reveal ``text`` (typewriter in place, then any overflow). */
  async finish(text: string): Promise<number> {
    this.done = true;
    await Promise.all(this.loops);
    const chunks = splitForTelegram(text);
    let sent = 0;
    if (this.placeholder !== null) {
      const first = chunks.shift() ?? "";
      const chars = cps(first);
      if (this.animate && chars.length > 80) {
        for (const frac of [0.35, 0.7]) {
          await this.tg.call("editMessageText", {
            chat_id: this.chatId, message_id: this.placeholder,
            text: chars.slice(0, Math.floor(chars.length * frac)).join("") + " ▍",
          });
          await this.sleep(350);
        }
      }
      const ok = await this.tg.call("editMessageText", { chat_id: this.chatId, message_id: this.placeholder, text: first });
      if (ok) sent++;
      else chunks.unshift(first); // edit refused => send as a normal message
    }
    for (const c of chunks) if (await this.tg.call("sendMessage", { chat_id: this.chatId, text: c })) sent++;
    return sent;
  }
}

