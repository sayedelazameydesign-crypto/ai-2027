/** PostgREST with the server-side service_role key (never sent to clients). */
export class PostgrestCeliaStore implements CeliaStore {
  constructor(private url: string, private key: string, private fetchFn: Fetch = fetch) {}

  private async req(path: string, init: RequestInit = {}, prefer?: string): Promise<unknown> {
    const headers: Record<string, string> = { apikey: this.key, "Content-Type": "application/json" };
    if (this.key.startsWith("eyJ")) headers["Authorization"] = `Bearer ${this.key}`;
    if (prefer) headers["Prefer"] = prefer;
    const res = await this.fetchFn(`${this.url.replace(/\/+$/, "")}/rest/v1/${path}`, { ...init, headers });
    const text = await res.text();
    if (!res.ok) throw new Error(`postgrest ${path.split("?")[0]} HTTP ${res.status}`); // body not echoed
    return text ? JSON.parse(text) : null;
  }
  private rpc(name: string, args: Record<string, unknown>) {
    return this.req(`rpc/${name}`, { method: "POST", body: JSON.stringify(args) });
  }
  async claimUpdate(updateId: number) {
    return (await this.rpc("celia_claim_update", { p_update_id: updateId })) === true;
  }
  async loadMemory() {
    return (await this.req("celia_memory?select=id,kind,text,source,created_at,confidence&order=id.asc")) as MemoryRecord[];
  }
  async applyChange(change: Change) {
    if (!change) return;
    if ("insert" in change) {
      await this.req("celia_memory", { method: "POST", body: JSON.stringify(change.insert) }, "return=minimal");
    } else {
      await this.req(`celia_memory?id=eq.${change.delete}`, { method: "DELETE" }, "return=minimal");
    }
  }
  async loadTurns(chatId: string, limit: number) {
    const rows = (await this.req(
      `celia_turns?select=role,content&chat_id=eq.${encodeURIComponent(chatId)}&order=id.desc&limit=${limit}`,
    )) as Turn[];
    return rows.reverse();
  }
  async appendTurns(chatId: string, user: string, assistant: string) {
    await this.rpc("celia_append_turns", { p_chat_id: chatId, p_user: user, p_assistant: assistant, p_keep: 40 });
  }
  async healthz() {
    await this.req("celia_memory?select=id&limit=1");
    return true;
  }
  async relayPush(updateId: number, payload: unknown) {
    await this.req(
      "celia_relay?on_conflict=update_id",
      { method: "POST", body: JSON.stringify({ update_id: updateId, payload }) },
      "resolution=ignore-duplicates,return=minimal",
    );
  }
  async relayFetch(offset: number | null, limit: number) {
    const out = await this.rpc("celia_relay_fetch", { p_offset: offset, p_limit: limit });
    return Array.isArray(out) ? out : [];
  }
  async loadOwners() {
    const rows = (await this.req("celia_config?select=value&key=eq.owners")) as { value: unknown }[];
    const v = rows?.[0]?.value;
    return Array.isArray(v) ? v.map(String) : [];
  }
  async saveOwners(owners: string[]) {
    await this.req(
      "celia_config?on_conflict=key",
      { method: "POST", body: JSON.stringify({ key: "owners", value: owners, updated_at: new Date().toISOString() }) },
      "resolution=merge-duplicates,return=minimal",
    );
  }
  async memoryReplace(rows: MemoryRecord[]) {
    return Number(await this.rpc("celia_memory_replace", { p_rows: rows }));
  }
}

