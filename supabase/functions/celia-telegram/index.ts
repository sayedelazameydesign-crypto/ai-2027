// ------------------------------------------------------------ normalization
// Python's \w / \b are Unicode-aware; JavaScript's are ASCII-only. These
// reproduce Python semantics exactly (\w == letters, numbers, underscore).
const W = "[\\p{L}\\p{N}_]";
const B = `(?:(?<=${W})(?!${W})|(?<!${W})(?=${W}))`;
const D = "\\p{Nd}";

const DIGITS: Record<string, string> = {};
Array.from("۰۱۲۳۴۵۶۷۸۹٠١٢٣٤٥٦٧٨٩").forEach((c, i) => (DIGITS[c] = String(i % 10)));
const ARABIC_DIACRITICS = /[\u0610-\u061A\u064B-\u065F\u0670\u06D6-\u06ED]/gu;
const PERSONA_DIACRITICS = /[\u0610-\u061A\u064B-\u065F\u0670\u06D6-\u06ED\u0640]/gu;

function foldArabic(t: string): string {
  return t.replace(/[أإآ]/g, "ا").replace(/ى/g, "ي").replace(/ة/g, "ه");
}

/** python-2027 celia_memory.normalize_bilingual_text. */
export function normalizeBilingual(text: string): string {
  let t = text.normalize("NFKC").replace(/[۰-۹٠-٩]/g, (c) => DIGITS[c]).toLowerCase();
  t = foldArabic(t.replace(ARABIC_DIACRITICS, ""));
  return t.replace(/\s+/gu, " ").trim();
}

/** python-2027 celia_persona.normalize (keyword matching). */
export function normalizeForMode(text: string): string {
  let t = foldArabic(text.toLowerCase().replace(PERSONA_DIACRITICS, ""));
  t = t.replace(/[^\p{L}\p{N}_\s]/gu, " ");
  return " " + t.replace(/\s+/gu, " ").trim() + " ";
}

