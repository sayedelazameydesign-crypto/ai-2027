def requirements_agent(ctx: HandlerContext) -> StepResult:
    """Turn the goal into a tiny requirements document."""
    doc = (
        "# Requirements\n\n"
        f"Goal: {ctx.goal}\n\n"
        "1. Produce a runnable Python module.\n"
        "2. Produce a static HTML page that imports nothing remote.\n"
        "3. Prove both files exist by SHA-256.\n"
    )
    path = _write(_sync_safe_target(ctx, f"demo/{ctx.task_id}/REQUIREMENTS.md"), doc)
    return StepResult(
        ok=True,
        summary="requirements drafted",
        output=doc[:400],
        artifacts=(_artifact(ctx, path, kind="document"),),
        evidence={"bytes": path.stat().st_size},
        duration_ms=1.0,
    )


def backend_agent(ctx: HandlerContext) -> StepResult:
    """Write a real module that the QA step can actually compile."""
    source = (
        '"""Generated by the fleet demo — deterministic, stdlib only."""\n\n'
        "def add(a: int, b: int) -> int:\n"
        '    """Return the sum of two integers."""\n'
        "    return a + b\n\n"
        "def health() -> dict[str, bool]:\n"
        '    """Report liveness for the demo server contract."""\n'
        '    return {"ok": True}\n'
    )
    path = _write(_sync_safe_target(ctx, f"demo/{ctx.task_id}/app.py"), source)
    return StepResult(
        ok=True,
        summary="backend module written",
        output=source,
        artifacts=(_artifact(ctx, path, kind="code"),),
        evidence={"lines": len(source.splitlines())},
    )


def frontend_agent(ctx: HandlerContext) -> StepResult:
    """Write a self-contained HTML page (no remote assets — repohouse rule)."""
    html = (
        "<!doctype html>\n<html lang=\"en\"><head><meta charset=\"utf-8\">"
        "<title>Fleet demo</title></head>\n<body><h1>Fleet demo</h1>"
        "<p>Rendered from a verified artifact.</p></body></html>\n"
    )
    path = _write(_sync_safe_target(ctx, f"demo/{ctx.task_id}/index.html"), html)
    return StepResult(
        ok=True,
        summary="frontend page written",
        output=html,
        artifacts=(_artifact(ctx, path, kind="html"),),
        evidence={"remote_scripts": 0},
    )


def qa_agent(ctx: HandlerContext) -> StepResult:
    """Compile the generated module for real and report test counts."""
    module = _sync_safe_target(ctx, f"demo/{ctx.task_id}/app.py")
    if not module.is_file():
        return StepResult(ok=False, error="app.py is missing; nothing to test")
    clean_env = {**os.environ, "PYTHONDONTWRITEBYTECODE": "1"}
    proc = subprocess.run(  # noqa: S603 - fixed argv, no shell
        [
            sys.executable,
            "-c",
            "import sys; compile(open(sys.argv[1], encoding='utf-8').read(), sys.argv[1], 'exec')",
            str(module),
        ],
        capture_output=True,
        text=True,
        timeout=20,
        check=False,
        env=clean_env,
    )
    if proc.returncode != 0:
        return StepResult(
            ok=False,
            error=f"py_compile failed: {proc.stderr[:300]}",
            evidence={"exit_code": proc.returncode},
        )
    # Import the generated module in a subprocess to assert its behaviour.
    probe = subprocess.run(  # noqa: S603 - fixed argv, no shell
        [
            sys.executable,
            "-c",
            "import importlib.util,json,sys;"
            "spec=importlib.util.spec_from_file_location('app',sys.argv[1]);"
            "m=importlib.util.module_from_spec(spec);spec.loader.exec_module(m);"
            "print(json.dumps({'sum':m.add(2,3),'health':m.health()}))",
            str(module),
        ],
        capture_output=True,
        text=True,
        timeout=20,
        check=False,
        env=clean_env,
    )
    if probe.returncode != 0:
        return StepResult(
            ok=False,
            error=f"behaviour probe failed: {probe.stderr[:300]}",
            evidence={"exit_code": probe.returncode},
        )
    payload = json.loads(probe.stdout)
    return StepResult(
        ok=True,
        summary="compile + behaviour probe passed",
        output=probe.stdout.strip(),
        evidence={
            "exit_code": 0,
            "tests_run": 2,
            "tests_failed": 0,
            "json": payload,
        },
        artifacts=(_artifact(ctx, module, kind="code"),),
    )


def docs_agent(ctx: HandlerContext) -> StepResult:
    """Flaky on purpose: fails on attempt 1, succeeds on attempt 2.

    This is how the demo shows *retry with backoff* doing real work rather than
    being described in a README.
    """
    if ctx.attempt < 2:
        return StepResult(ok=False, error="transient failure: template cache cold")
    path = _write(
        _sync_safe_target(ctx, f"demo/{ctx.task_id}/README.md"),
        f"# Demo\n\nTask `{ctx.task_id}` built by the fleet on attempt {ctx.attempt}.\n",
    )
    return StepResult(
        ok=True,
        summary=f"docs written on attempt {ctx.attempt}",
        output="README.md",
        artifacts=(_artifact(ctx, path, kind="document"),),
    )


def optional_metrics_agent(ctx: HandlerContext) -> StepResult:
    """Always fails; declared non-critical so the run degrades instead of dying."""
    return StepResult(ok=False, error="metrics backend is not configured in this demo")


def reviewer_agent(ctx: HandlerContext) -> StepResult:
    """Deterministic independent reviewer used for ``independent_review`` checks."""
    target = str(ctx.inputs.get("review_target", ""))
    problems = [p for p in ("unverified", "TODO", "FIXME") if p in target]
    if problems:
        return StepResult(ok=False, error=f"reviewer found {problems}")
    return StepResult(
        ok=True,
        summary="reviewer approved",
        output="approved",
        evidence={"verdict_note": "reviewer approved: no unresolved markers"},
    )


