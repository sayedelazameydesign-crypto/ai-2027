def build_demo_registry() -> AgentRegistry:
    """Register the deterministic demo fleet with explicit capabilities."""
    registry = AgentRegistry()
    registry.register(
        AgentSpec(
            name="analyst",
            role="turn a goal into requirements",
            capabilities=("requirements",),
            produces=("document",),
            cost_tier=CostTier.LOCAL,
            requires_evidence=(EvidenceKind.OUTPUT_NON_EMPTY.value, EvidenceKind.ARTIFACT_SHA256.value),
        ),
        requirements_agent,
    )
    registry.register(
        AgentSpec(
            name="backend-engineer",
            role="write the Python module",
            capabilities=("backend",),
            produces=("code",),
            cost_tier=CostTier.LOCAL,
            requires_evidence=(EvidenceKind.ARTIFACT_SHA256.value,),
        ),
        backend_agent,
    )
    registry.register(
        AgentSpec(
            name="frontend-engineer",
            role="write the static page",
            capabilities=("frontend",),
            produces=("html",),
            cost_tier=CostTier.LOCAL,
            requires_evidence=(EvidenceKind.ARTIFACT_SHA256.value,),
        ),
        frontend_agent,
    )
    registry.register(
        AgentSpec(
            name="qa-engineer",
            role="compile and probe the generated module",
            capabilities=("qa",),
            produces=("report",),
            cost_tier=CostTier.LOCAL,
            requires_evidence=(
                EvidenceKind.EXIT_CODE_ZERO.value,
                EvidenceKind.TEST_PASSED.value,
                EvidenceKind.ARTIFACT_SHA256.value,
            ),
        ),
        qa_agent,
    )
    registry.register(
        AgentSpec(
            name="technical-writer",
            role="write the README (retries once by design)",
            capabilities=("docs",),
            produces=("document",),
            cost_tier=CostTier.LOCAL,
            max_attempts=3,
            requires_evidence=(EvidenceKind.ARTIFACT_SHA256.value,),
        ),
        docs_agent,
    )
    registry.register(
        AgentSpec(
            name="metrics-collector",
            role="optional metrics (never configured in the demo)",
            capabilities=("metrics",),
            produces=("metrics",),
            cost_tier=CostTier.LOCAL,
            max_attempts=1,
            fallbacks=(),
        ),
        optional_metrics_agent,
    )
    registry.register(
        AgentSpec(
            name="reviewer",
            role="independent reviewer for verified work",
            capabilities=("review",),
            produces=("verdict",),
            cost_tier=CostTier.LOCAL,
            requires_evidence=(EvidenceKind.OUTPUT_NON_EMPTY.value,),
        ),
        reviewer_agent,
    )
    return registry


def build_demo_task(task_id: str, *, goal: str | None = None) -> TaskSpec:
    """A five-step DAG that exercises parallelism, retry, degradation and review."""
    steps = (
        PlanStep(
            step_id="requirements",
            agent="analyst",
            action="draft requirements",
            verification=(EvidenceKind.ARTIFACT_SHA256.value, EvidenceKind.OUTPUT_NON_EMPTY.value),
        ),
        PlanStep(
            step_id="backend",
            agent="backend-engineer",
            action="write app.py",
            depends_on=("requirements",),
            verification=(EvidenceKind.ARTIFACT_SHA256.value,),
        ),
        PlanStep(
            step_id="frontend",
            agent="frontend-engineer",
            action="write index.html",
            depends_on=("requirements",),
            verification=(EvidenceKind.ARTIFACT_SHA256.value,),
        ),
        PlanStep(
            step_id="qa",
            agent="qa-engineer",
            action="compile and probe app.py",
            depends_on=("backend",),
            verification=(
                EvidenceKind.EXIT_CODE_ZERO.value,
                EvidenceKind.TEST_PASSED.value,
                EvidenceKind.ARTIFACT_SHA256.value,
            ),
            inputs={
                "json_schema": {
                    "type": "object",
                    "required": ["sum", "health"],
                    "properties": {"sum": {"type": "integer"}},
                }
            },
        ),
        PlanStep(
            step_id="docs",
            agent="technical-writer",
            action="write README.md",
            depends_on=("requirements",),
            verification=(EvidenceKind.ARTIFACT_SHA256.value,),
        ),
        PlanStep(
            step_id="metrics",
            agent="metrics-collector",
            action="export optional metrics",
            depends_on=("qa",),
            critical=False,
            verification=(EvidenceKind.OUTPUT_NON_EMPTY.value,),
        ),
    )
    return TaskSpec(
        task_id=task_id,
        goal=goal or "Build a tiny verified app (module + page + tests) with a fleet",
        steps=steps,
        created_by="demo",
    )


def seed_marker(path: Path, value: str) -> None:
    """Small helper for external scripts that need a filesystem side effect."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(value, encoding="utf-8")


def sleep_ms(ms: float) -> None:  # pragma: no cover - convenience for demos
    """Sleep for ``ms`` milliseconds."""
    time.sleep(ms / 1000.0)


def env_flag(name: str, default: bool = False) -> bool:  # pragma: no cover - CLI helper
    """Read a boolean environment flag without importing anything external."""
    raw = os.environ.get(name)
    if raw is None:
        return default
    return raw.strip().lower() in {"1", "true", "yes", "on"}


def summarize_evidence(report: dict[str, Any]) -> str:
    """Render a compact, honest summary of a run report."""
    verified = report.get("verified", 0)
    executed = report.get("executed", 0)
    return (
        f"status={report.get('status')} executed={executed} verified={verified} "
        f"failed={report.get('failed')} skipped={report.get('skipped')} "
        f"dead_letters={report.get('dead_letters')} degraded={report.get('degraded')} "
        f"waves={report.get('waves')}"
    )
