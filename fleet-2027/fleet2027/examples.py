"""A deterministic local fleet used by the CLI demo, tests and the evidence gate.

These are **real** agents in the sense that matters for durability and
verification: they write real files, compute real SHA-256 digests, run a real
Python compile check, and one of them fails on purpose so that retry,
dead-letter and graceful degradation are exercised every single run. They are
**not** LLM calls — this repository has a standing rule against claiming a
model was called when it was not, and the demo prints that limitation itself.
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
import time
from pathlib import Path
from typing import Any

from .contracts import (
    AgentSpec,
    ArtifactRef,
    CostTier,
    EvidenceKind,
    PlanStep,
    StepResult,
    TaskSpec,
)
from .registry import AgentRegistry, HandlerContext


def _write(path: Path, text: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path


def _sync_safe_target(ctx: HandlerContext, relative: str) -> Path:
    """Resolve a demo output path inside the workspace (never outside it)."""
    target = (ctx.workspace_root / relative).resolve()
    root = ctx.workspace_root.resolve()
    if target != root and root not in target.parents:
        raise ValueError(f"demo agent refused to write outside the workspace: {relative}")
    return target


def _artifact(ctx: HandlerContext, path: Path, *, kind: str) -> ArtifactRef:
    """Describe a written file with a *workspace-relative* path.

    Relative paths are deliberate: the verifier must be able to re-hash the
    artifact on a machine that does not share the producer's absolute paths.
    """
    return ArtifactRef.from_file(
        str(path),
        kind=kind,
        record_path=path.relative_to(ctx.workspace_root.resolve()).as_posix(),
    )


