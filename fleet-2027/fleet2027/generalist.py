"""A generalist fleet: agents that can carry out an intent plan, locally.

Why this module exists
----------------------
The intent layer (:mod:`kernel2027.intent`) turns one plain sentence into a plan
whose agents are named by *role*: ``planner``, ``builder``, ``verifier``,
``researcher``, ``writer``, ``teacher``. The demo registry names agents after
*jobs*: ``analyst``, ``backend-engineer``, ``qa-engineer``. Neither is wrong, but
they do not meet — and the first end-to-end run of the feature dead-lettered for
exactly that reason. A durable task was created, marked failed, and the user was
left holding a broken task instead of a clear "this system cannot do that yet".

So this module supplies the missing half: deterministic, local, dependency-free
agents that answer to the role names the intent layer emits. They are **real**
in the only sense this repository accepts — they write real files, compute real
digests, and are checked by a verifier that re-hashes what it finds. They are
**not** model calls, and they never claim to be: every artifact they produce
says so in its own header, because a stand-in that pretends to be the real thing
is worse than no stand-in at all.

What that means for the user
---------------------------
With this registry, "اعمل لي موقع" runs end to end on a machine with no API key,
no network and no spend, and produces a file they can open. The content is
deliberately plain — it is a scaffold plus a honest note — but the *pipeline*
around it is the production one: durable steps, idempotency keys, a verification
step that fails closed, and an audit chain that can be checked afterwards.

The scaffolding is the point. When a real model is wired in later, it replaces
the body of ``_draft`` and nothing else changes: the plan, the ordering, the
evidence and the verification all stay identical.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from .contracts import AgentSpec, ArtifactRef, CostTier, EvidenceKind, StepResult
from .registry import AgentRegistry, HandlerContext

#: Written into every generated file. Non-negotiable: a reader must be able to
#: tell that no model produced this, without reading any source code.
PROVENANCE = (
    "<!-- Generated by ai-2027 generalist fleet (local, deterministic). "
    "No language model was called. Content is a scaffold: replace it with real copy. -->\n"
)

#: Which artifact each domain should produce, keyed by the domain the intent
#: layer reports. Unknown domains fall back to ``notes.md`` rather than failing:
#: a wrong filename is a smaller failure than a plan that cannot run.
_TARGETS: dict[str, tuple[str, str]] = {
    "website": ("index.html", "html"),
    "document": ("document.md", "markdown"),
    "research": ("report.md", "markdown"),
    "organize": ("plan.md", "markdown"),
    "learn": ("explanation.md", "markdown"),
    "travel": ("itinerary.md", "markdown"),
    "business": ("business-plan.md", "markdown"),
    "code": ("change.md", "markdown"),
    "email": ("draft.txt", "text"),
}


def _safe_dir(ctx: HandlerContext) -> Path:
    """Create and return ``intent/<task>/`` inside the workspace, never outside."""
    root: Path = ctx.workspace_root.resolve()
    target = (root / "intent" / ctx.task_id).resolve()
    if target != root and root not in target.parents:
        raise ValueError(f"refused to write outside the workspace: {ctx.task_id}")
    target.mkdir(parents=True, exist_ok=True)
    return target


def _domain(ctx: HandlerContext) -> str:
    """Read the domain the intent layer recorded, defaulting to a safe value."""
    settings = ctx.inputs.get("settings")
    if isinstance(settings, dict):
        domain = settings.get("domain")
        if isinstance(domain, str) and domain:
            return domain
    meta = ctx.inputs.get("domain")
    return meta if isinstance(meta, str) and meta else "document"


def _settings(ctx: HandlerContext) -> dict[str, str]:
    """The resolved settings map, or an empty one. Never raises."""
    raw = ctx.inputs.get("settings")
    return {str(k): str(v) for k, v in raw.items()} if isinstance(raw, dict) else {}


