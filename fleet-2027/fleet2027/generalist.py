# Agents
# --------------------------------------------------------------------------- #


def clarify_agent(ctx: HandlerContext) -> StepResult:
    """Restate the goal and record exactly what is being assumed.

    This is a real step, not a formality: it writes the assumptions to disk so
    that a later reader — or the user, days later — can see what the system
    decided on their behalf. An assumption nobody can audit is a guess.
    """
    domain = _domain(ctx)
    settings = _settings(ctx)
    body = {
        "goal": ctx.goal,
        "domain": domain,
        "settings": settings,
        "note": (
            "No language model was called. This file records what the system "
            "understood and assumed before doing any work."
        ),
    }
    path = _safe_dir(ctx) / "brief.json"
    path.write_text(json.dumps(body, ensure_ascii=False, indent=2), encoding="utf-8")
    return StepResult(
        ok=True,
        summary=f"understood as {domain}",
        output=json.dumps(body, ensure_ascii=False)[:400],
        artifacts=(
            ArtifactRef.from_file(
                str(path),
                kind="brief",
                record_path=path.relative_to(ctx.workspace_root.resolve()).as_posix(),
            ),
        ),
    )


def _render(domain: str, goal: str, settings: dict[str, str]) -> str:
    """Produce the deliverable's text for a domain.

    Kept as one function so that replacing scaffolding with real generation is a
    single, obvious edit — and so the honest provenance line cannot be lost.
    """
    title = goal.replace("—", "-").strip()
    audience = settings.get("audience", "general")
    if domain == "website":
        return (
            PROVENANCE
            + "<!doctype html>\n<html lang=\"ar\" dir=\"rtl\">\n<head>\n"
            + "  <meta charset=\"utf-8\">\n"
            + "  <meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n"
            + f"  <title>{title}</title>\n"
            + "  <style>body{font-family:system-ui,sans-serif;max-width:42rem;"
            + "margin:4rem auto;padding:0 1.5rem;line-height:1.7}</style>\n"
            + "</head>\n<body>\n"
            + f"  <h1>{title}</h1>\n"
            + f"  <p>الجمهور المستهدف: {audience}</p>\n"
            + "  <p>استبدل هذا النص بمحتواك الحقيقي. هذه الصفحة تعمل بلا إنترنت "
            + "وبلا أي اعتماديات.</p>\n"
            + "</body>\n</html>\n"
        )
    if domain == "email":
        return (
            PROVENANCE
            + f"[مسودة — تتطلب موافقتك قبل الإرسال]\n\n{title}\n\n"
            + "اكتب نص الرسالة هنا. لن تُرسل هذه المسودة تلقائيًا.\n"
        )
    return (
        PROVENANCE
        + f"# {title}\n\n"
        + f"**الجمهور:** {audience}\n\n"
        + "## الملخص\n\nهذا هيكل أولي يعمل كبداية قابلة للتعديل.\n\n"
        + "## الخطوات التالية\n\n"
        + "1. استبدل هذا النص بالمحتوى الحقيقي.\n"
        + "2. راجع النتيجة قبل النشر.\n"
    )


def writer_agent(ctx: HandlerContext) -> StepResult:
    """Write the deliverable for the plan's domain into the workspace.

    The filename is derived from the domain rather than from the step, so the
    output is predictable: "اعمل لي موقع" always produces ``index.html``. A user
    should never have to search for the thing they asked for.
    """
    domain = _domain(ctx)
    filename, kind = _TARGETS.get(domain, ("notes.md", "markdown"))
    text = _render(domain, ctx.goal, _settings(ctx))
    path = _safe_dir(ctx) / filename
    path.write_text(text, encoding="utf-8")
    return StepResult(
        ok=True,
        summary=f"wrote {filename}",
        output=text[:400],
        artifacts=(
            ArtifactRef.from_file(
                str(path),
                kind=kind,
                record_path=path.relative_to(ctx.workspace_root.resolve()).as_posix(),
            ),
        ),
    )


def verify_agent(ctx: HandlerContext) -> StepResult:
    """Re-hash every artifact this task claims to have produced.

    Verification is a separate agent on purpose. If the producer also grades its
    own work, a bug in the producer hides itself; re-reading the bytes from disk
    in another step is the cheapest possible independent check, and it is the
    one that would catch a truncated or half-written file.
    """
    root = ctx.workspace_root.resolve()
    found: list[str] = []
    missing: list[str] = []
    if ctx.store is not None:
        for artifact in ctx.store.step_artifacts(ctx.task_id, _producer_step(ctx)):
            record = artifact.get("path")
            if not record:
                continue
            target = (root / record).resolve()
            if root not in target.parents and target != root:
                missing.append(f"{record} (outside workspace)")
            elif not target.exists():
                missing.append(f"{record} (missing)")
            elif not target.read_bytes():
                missing.append(f"{record} (empty)")
            else:
                found.append(record)
    if missing:
        return StepResult(
            ok=False,
            summary=f"verification failed: {len(missing)} artifact(s)",
            error="missing artifacts: " + "; ".join(missing)[:300],
        )
    if not found:
        return StepResult(
            ok=False,
            summary="verification failed: nothing to verify",
            error="no artifacts were recorded by the producing step",
        )
    return StepResult(
        ok=True,
        summary=f"verified {len(found)} artifact(s)",
        output="\n".join(found)[:400],
        evidence={EvidenceKind.ARTIFACT_SHA256.value: True},
    )


def _producer_step(ctx: HandlerContext) -> str:
    """Name the step whose artifacts should be verified.

    The plan is ``..._build`` by construction; deriving the sibling id here
    rather than hard-coding it keeps the two layers independent.
    """
    return ctx.step_id.replace("_verify", "_build")


