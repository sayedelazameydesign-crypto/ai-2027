def build_generalist_registry() -> AgentRegistry:
    """A registry whose agents answer to the intent layer's role names.

    Every agent is ``LOCAL`` cost tier with a single attempt: these are pure
    functions of their inputs, so retrying them is pointless. A real model-backed
    fleet would set ``max_attempts`` higher and let the kernel's retry/breaker
    decide — the surrounding plan does not change.
    """
    registry = AgentRegistry()
    registry.register(
        AgentSpec(
            name="planner",
            role="understands the request and records its assumptions",
            capabilities=("clarify",),
            produces=("brief",),
            cost_tier=CostTier.LOCAL,
            requires_evidence=(EvidenceKind.OUTPUT_NON_EMPTY.value,),
            max_attempts=1,
        ),
        clarify_agent,
    )
    registry.register(
        AgentSpec(
            name="builder",
            role="writes the deliverable into the workspace",
            capabilities=("write",),
            produces=("artifact",),
            cost_tier=CostTier.LOCAL,
            requires_evidence=(EvidenceKind.ARTIFACT_SHA256.value,),
            max_attempts=1,
        ),
        writer_agent,
    )
    registry.register(
        AgentSpec(
            name="writer",
            role="writes documents and drafts",
            capabilities=("draft",),
            produces=("artifact",),
            cost_tier=CostTier.LOCAL,
            requires_evidence=(EvidenceKind.ARTIFACT_SHA256.value,),
            max_attempts=1,
        ),
        writer_agent,
    )
    registry.register(
        AgentSpec(
            name="researcher",
            role="writes a report from locally available material",
            capabilities=("research",),
            produces=("artifact",),
            cost_tier=CostTier.LOCAL,
            requires_evidence=(EvidenceKind.ARTIFACT_SHA256.value,),
            max_attempts=1,
        ),
        writer_agent,
    )
    registry.register(
        AgentSpec(
            name="teacher",
            role="writes an explanation",
            capabilities=("explain",),
            produces=("artifact",),
            cost_tier=CostTier.LOCAL,
            requires_evidence=(EvidenceKind.ARTIFACT_SHA256.value,),
            max_attempts=1,
        ),
        writer_agent,
    )
    registry.register(
        AgentSpec(
            name="verifier",
            role="re-reads produced artifacts and fails closed",
            capabilities=("verify",),
            produces=("verdict",),
            cost_tier=CostTier.LOCAL,
            # A verifier's product is a *verdict*, so demanding ARTIFACT_SHA256
            # here would ask it to prove it wrote a file it never writes. This
            # single wrong field dead-lettered every intent task on the first
            # end-to-end run — and it was only visible by running one.
            requires_evidence=(EvidenceKind.OUTPUT_NON_EMPTY.value,),
            max_attempts=1,
        ),
        verify_agent,
    )
    return registry


def registry_index() -> dict[str, Any]:
    """Small helper for tests and docs: the role names this fleet provides."""
    registry = build_generalist_registry()
    return {
        "names": registry.names,
        "capabilities": tuple(registry.capabilities),
    }
