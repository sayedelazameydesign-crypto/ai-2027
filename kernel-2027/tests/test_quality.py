"""Tests for the quality ruler.

The most important test in this file is :meth:`HonestyTests.test_the_scaffold_is_not_usable`.
The first version of ``kernel2027.quality`` rated the deterministic scaffold at
**0.94** and called it usable. The scaffold contains the sentence "replace this
text with your real content" — it is an admitted stub. A scorer that flatters a
stub is worse than no scorer, because it produces numbers people will cite.

Everything here is deterministic and offline: same bytes, same score, forever.
"""

from __future__ import annotations

import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from kernel2027.quality import (
    USABLE_FLOOR,
    WEIGHTS,
    score,
    score_file,
)

#: The real scaffold, copied from what ``fleet2027.generalist._render`` emits.
SCAFFOLD = """<!-- Generated by ai-2027 generalist fleet (local, deterministic). \
No language model was called. Content is a scaffold: replace it with real copy. -->
<!doctype html>
<html lang="ar" dir="rtl">
<head><meta charset="utf-8"><title>بناء موقع</title></head>
<body>
  <h1>بناء موقع</h1>
  <p>الجمهور المستهدف: general</p>
  <p>استبدل هذا النص بمحتواك الحقيقي. هذه الصفحة تعمل بلا إنترنت وبلا أي اعتماديات.</p>
</body>
</html>
"""

#: A page a person would actually keep.
REAL = """<!doctype html>
<html lang="ar" dir="rtl">
<head><meta charset="utf-8"><title>متجر النور — عسل بلدي</title></head>
<body>
  <h1>متجر النور</h1>
  <p>نبيع العسل البلدي الخام من مناحل الفيوم، مع شهادة تحليل لكل دفعة. العسل
  يُعبأ بعد الطلب لا قبله، ويصل خلال ثمانٍ وأربعين ساعة لجميع محافظات مصر.</p>
  <h2>لماذا نختلف</h2>
  <p>كل برطمان يحمل رقم الدفعة وتاريخ الجني، لأن العميل يستحق أن يعرف من أين
  جاء ما يأكله. السعر يشمل التوصيل، ولا توجد رسوم مخفية عند الدفع.</p>
</body>
</html>
"""


class HonestyTests(unittest.TestCase):
    """The scorer must not flatter the scaffold. This is the whole point."""

    def test_the_scaffold_is_not_usable(self) -> None:
        """It says 'replace this text'. It is not a deliverable."""
        report = score("website", SCAFFOLD)
        self.assertFalse(
            report.usable,
            f"the scaffold scored {report.score} and was called usable",
        )
        self.assertIn("substance", report.failures())

    def test_real_content_is_usable(self) -> None:
        """A floor that rejects everything is as useless as one that accepts all."""
        report = score("website", REAL)
        self.assertTrue(report.usable, f"hand-written content scored {report.score}")

    def test_real_content_outranks_the_scaffold_by_a_wide_margin(self) -> None:
        """If a stub and a real page score alike, the ruler has no resolution."""
        gap = score("website", REAL).score - score("website", SCAFFOLD).score
        self.assertGreater(gap, 0.20, f"only {gap:.2f} separates a stub from real work")

    def test_an_empty_file_scores_near_zero(self) -> None:
        report = score("website", "")
        self.assertLess(report.score, 0.30)
        self.assertFalse(report.usable)

    def test_the_floor_is_between_the_two_measured_points(self) -> None:
        """The threshold must be justified by data, not chosen for comfort."""
        self.assertGreater(USABLE_FLOOR, score("website", SCAFFOLD).score)
        self.assertLess(USABLE_FLOOR, score("website", REAL).score)


class DeterminismTests(unittest.TestCase):
    """A number nobody can reproduce is an opinion."""

    def test_the_same_bytes_always_give_the_same_score(self) -> None:
        first = score("website", REAL).to_dict()
        second = score("website", REAL).to_dict()
        self.assertEqual(first, second)

    def test_scoring_is_not_order_dependent(self) -> None:
        """Scoring one file must not change the score of the next."""
        before = score("website", REAL).score
        for domain in ("travel", "code", "email", "organize"):
            score(domain, "x" * 500)
        self.assertEqual(score("website", REAL).score, before)

    def test_no_network_and_no_provider(self) -> None:
        import ast

        source = (
            Path(__file__).resolve().parent.parent / "kernel2027" / "quality.py"
        ).read_text(encoding="utf-8")
        imported: set[str] = set()
        for node in ast.walk(ast.parse(source)):
            if isinstance(node, ast.Import):
                imported.update(a.name.split(".")[0] for a in node.names)
            elif isinstance(node, ast.ImportFrom) and node.module:
                imported.add(node.module.split(".")[0])
        for forbidden in ("httpx", "requests", "socket", "urllib", "http"):
            self.assertNotIn(forbidden, imported)

    def test_scoring_a_file_matches_scoring_its_bytes(self) -> None:
        """Reading from disk must not change the answer."""
        import tempfile

        with tempfile.NamedTemporaryFile(
            "w", suffix=".html", delete=False, encoding="utf-8"
        ) as handle:
            handle.write(REAL)
            path = handle.name
        try:
            self.assertEqual(
                score_file("website", path).to_dict(), score("website", REAL).to_dict()
            )
        finally:
            Path(path).unlink()


class CriterionTests(unittest.TestCase):
    """Each criterion must catch the failure it exists for."""

    def test_broken_html_fails_structure(self) -> None:
        broken = "<div><p>text without closing"
        report = score("website", broken * 20)
        self.assertLess({c.name: c.score for c in report.criteria}["structure"], 0.6)

    def test_remote_assets_fail_usability(self) -> None:
        """A page needing a network to render is not a finished page."""
        with_cdn = REAL + '<link href="//cdn.example.com/x.css" rel="stylesheet">'
        criterion = {c.name: c for c in score("website", with_cdn).criteria}["usable"]
        self.assertLess(criterion.score, 0.5)
        self.assertIn("remote", criterion.reason)

    def test_filler_is_penalised(self) -> None:
        padded = (
            REAL
            + "<p>Certainly! As an AI, I would be happy to help. Hope this helps.</p>"
        )
        report = score("website", padded)
        self.assertLess({c.name: c.score for c in report.criteria}["no_filler"], 0.6)

    def test_unsourced_authority_is_penalised(self) -> None:
        """'Studies show' is authority a reader cannot check."""
        vague = REAL + "<p>Studies show that 87% of people prefer this.</p>"
        criterion = {c.name: c for c in score("website", vague).criteria}["honesty"]
        self.assertLess(criterion.score, 0.4)
        self.assertIn("unsourced", criterion.reason)

    def test_stating_a_limit_is_rewarded_not_punished(self) -> None:
        """An admitted assumption is what honesty looks like."""
        honest = REAL + "<p>السعر تقديري ويجب التحقق منه قبل الطلب.</p>"
        criterion = {c.name: c for c in score("website", honest).criteria}["honesty"]
        self.assertEqual(criterion.score, 1.0)

    def test_a_plan_without_steps_fails_relevance(self) -> None:
        report = score("organize", "مرحبا " * 100)
        criterion = {c.name: c for c in report.criteria}["relevance"]
        self.assertLess(criterion.score, 0.4)

    def test_a_short_answer_to_a_large_request_fails_completeness(self) -> None:
        report = score("research", "فيه بحث.")
        criterion = {c.name: c for c in report.criteria}["completeness"]
        self.assertLess(criterion.score, 0.2)


class ShapeTests(unittest.TestCase):
    """Small guarantees the report must keep for the benchmark to be comparable."""

    def test_every_criterion_is_weighted(self) -> None:
        report = score("website", REAL)
        for criterion in report.criteria:
            self.assertIn(criterion.name, WEIGHTS, f"{criterion.name} has no weight")

    def test_weights_sum_to_one(self) -> None:
        self.assertAlmostEqual(sum(WEIGHTS.values()), 1.0, places=6)

    def test_score_is_bounded(self) -> None:
        for text in ("", "x", REAL * 5, "<html>" * 100):
            self.assertGreaterEqual(score("website", text).score, 0.0)
            self.assertLessEqual(score("website", text).score, 1.0)

    def test_every_criterion_explains_itself(self) -> None:
        for criterion in score("website", SCAFFOLD).criteria:
            self.assertTrue(criterion.reason.strip(), f"{criterion.name} has no reason")

    def test_failures_are_ordered_worst_first(self) -> None:
        report = score("website", SCAFFOLD)
        scores = {c.name: c.score for c in report.criteria}
        ordered = [scores[name] for name in report.failures()]
        self.assertEqual(ordered, sorted(ordered))

    def test_report_serialises(self) -> None:
        import json

        payload = score("travel", REAL).to_dict()
        self.assertIn("score", json.loads(json.dumps(payload)))


