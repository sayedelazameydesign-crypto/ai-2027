def _command(text: str) -> list[str] | None:
    """Parsed command as JSON, or None."""
    cmd = parse_memory_command(text)
    return None if cmd is None else [cmd.kind.value, cmd.argument]


def _session() -> list[list[object]]:
    """Run SESSION through PersonalMemory; record stage, reply and ids."""
    memory = PersonalMemory(ListMemoryBackend(), clock=lambda: NOW, max_records=5)
    steps: list[list[object]] = []
    for i, text in enumerate(SESSION):
        cmd = parse_memory_command(text)
        if cmd is None:
            raise ValueError(text)
        out = memory.execute_durably(cmd, source=f"telegram:{i}")
        steps.append([text, out.stage, out.reply, [r.id for r in memory.records]])
    return steps


def build_vectors() -> dict[str, object]:
    """All parity vectors from the python-2027 reference."""
    return {
        "now": NOW,
        "modes": [[t, detect_mode(t).value] for t in MODE_TEXTS],
        "commands": [[t, _command(t)] for t in PARSE_TEXTS],
        "sensitive": [[t, looks_sensitive(t)] for t in SENSITIVE_TEXTS],
        "kinds": [[t, classify_kind(t).value] for t in KIND_TEXTS],
        "prompts": {
            m.value: render_system_prompt(Audience.OWNER, m) for m in CeliaMode
        },
        "prompt_with_memories": render_system_prompt(
            Audience.OWNER, CeliaMode.EXECUTIVE, MEMORIES
        ),
        "memories_input": MEMORIES,
        "session": _session(),
        "session_max_records": 5,
    }


def build_spec_block() -> str:
    """The generated SPEC block embedded in index.ts."""
    spec = {"persona": persona_spec(), "memory": memory_spec()}
    body = json.dumps(spec, ensure_ascii=False, indent=2, sort_keys=True)
    return f"{BEGIN}\nexport const SPEC = {body} as const;\n{END}"


def render_index(source: str) -> str:
    """index.ts with a freshly generated SPEC block."""
    start, end = source.index(BEGIN), source.index(END) + len(END)
    return source[:start] + build_spec_block() + source[end:]


def vectors_text() -> str:
    """parity_vectors.json content."""
    return json.dumps(build_vectors(), ensure_ascii=False, indent=1, sort_keys=True) + "\n"


def main(argv: list[str]) -> int:
    """CLI: --write regenerates, otherwise check."""
    index_now = INDEX.read_text(encoding="utf-8")
    index_new = render_index(index_now)
    vectors_now = VECTORS.read_text(encoding="utf-8") if VECTORS.exists() else ""
    vectors_new = vectors_text()
    if "--write" in argv:
        INDEX.write_text(index_new, encoding="utf-8")
        VECTORS.write_text(vectors_new, encoding="utf-8")
        print("wrote", INDEX.relative_to(ROOT), "and", VECTORS.relative_to(ROOT))
        return 0
    stale = [p.name for p, a, b in ((INDEX, index_now, index_new), (VECTORS, vectors_now, vectors_new)) if a != b]
    if stale:
        print("stale (run with --write):", ", ".join(stale))
        return 1
    print("celia edge port is in sync with python-2027")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
